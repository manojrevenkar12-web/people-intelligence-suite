REPORTS = ROOT / "reports"


def money_at_stake() -> dict[str, float]:
    r = mart("fct_payroll_recon")
    over = r[r.status == "leaver_paid"].gross.sum()
    sal = r[r.status == "salary_mismatch"]
    under = (sal.expected_base_monthly - sal.payroll_base_monthly).sum()
    hrs = r[r.status == "hours_mismatch"]
    hours_over = (hrs.payroll_base_monthly - hrs.expected_base_monthly).sum()
    return {
        "paid_to_leavers": round(float(over), 2),
        "raises_not_paid": round(float(under), 2),
        "paid_for_hours_not_worked": round(float(hours_over), 2),
    }


def first_run(name: str) -> dict[str, Any] | None:
    p = REPORTS / "heldout" / name / "first_run.json"
    return json.loads(p.read_text()) if p.exists() else None


def pct(x: float | None) -> str:
    return "–" if x is None else f"{100 * x:.1f}%"


def eur(x: float) -> str:
    return f"€{x:,.0f}"


def markdown(res: dict[str, Any], stake: dict[str, float]) -> str:
    d, w, g = res["data"], res["workforce"], res["pay_gap"]
    rows = [
        ("Paid after leaving", "leaver_paid"),
        ("Missing from first payroll", "joiner_missing"),
        ("Raise in HiBob, not in payroll", "raise_not_in_payroll"),
        ("Part-time in HiBob, full time in payroll", "fte_mismatch"),
        ("Reports to someone who left", "manager_is_leaver"),
        ("No manager", "missing_manager"),
        ("Rehire created as a second person", "duplicate_rehire"),
        ("Approved raise never entered in HiBob", "comp_not_in_hibob"),
        ("Payroll file sent in cents", "vendor_cents_month"),
        ("Cost booked to the old department", "gl_old_cost_center"),
    ]
    out = [
        "# Results",
        "",
        "_Generated by `pis report` from `reports/results.json`. Do not edit by hand._",
        "",
        f"Reporting month {w['month']}: {w['headcount']} people ({w['fte']:.1f} FTE) in "
        + ", ".join(f"{k} {v}" for k, v in sorted(w["by_country"].items()))
        + f". Twelve-month attrition "
        f"{pct(w['attrition_12m'])}, voluntary {pct(w['voluntary_attrition_12m'])}.",
        "",
        "## Planted problems found",
        "",
        "| Problem | Planted | Flagged | Correct | Precision | Recall |",
        "|---|---:|---:|---:|---:|---:|",
    ]
    for label, k in rows:
        x = d[k]
        out.append(
            f"| {label} | {x['planted']} | {x['found']} | {x['true_positives']} | {pct(x['precision'])} | "
            f"{pct(x['recall'])} |"
        )
    pe = d["payroll_exceptions_total"]
    out += [
        "",
        f"{d['rows_checked']:,} person-months reconciled; {pe['rows']} exception rows for {pe['people']} "
        f"people, of whom {pe['people_not_planted']} were not planted. "
        f"The {d['gl_old_cost_center']['breaks']} GL breaks were all paired and explained "
        f"({d['gl_old_cost_center']['breaks_explained']} of {d['gl_old_cost_center']['breaks']}).",
        "",
        f"Money at stake: {eur(stake['paid_to_leavers'])} paid to people after they left, "
        f"{eur(stake['raises_not_paid'])} of approved raises not paid, "
        f"{eur(stake['paid_for_hours_not_worked'])} paid for hours not in the contract.",
        "",
        "## Pay equity",
        "",
        f"Adjusted gap overall (level, country and department held equal): {pct(g['overall']['adjusted_gap'])} "
        f"(standard error {pct(g['overall']['se'])}); raw median gap {pct(g['overall']['raw_gap'])}.",
        "",
        "| Department | Women | Men | Adjusted gap | 90% interval | Over 5% | Evidence |",
        "|---|---:|---:|---:|---:|:--:|:--:|",
    ]
    for x in res["pay_gap_detail"]["by_department"]:
        if x["suppressed"]:
            out.append(
                f"| {x['department']} | – | – | suppressed (fewer than {res['pay_gap_detail']['min_group']}) | | | |"
            )
            continue
        lo, hi = x["interval"]
        out.append(
            f"| {x['department']} | {x['women']} | {x['men']} | {pct(x['adjusted_gap'])} | "
            f"{pct(lo)} to {pct(hi)} | {'yes' if x['over_threshold'] else ''} | "
            f"{'yes' if x['evidence'] else ''} |"
        )
    out += ["", f"Planted gap: {', '.join(g['planted'])}; found: {'yes' if g['planted_found'] else 'no'}.", ""]
    dev = res["assistant_dev"]
    out += [
        "## Self-service assistant",
        "",
        "| Set | Questions | Correct | Answered when it should not | "
        "Handed over when it could answer | Wrong section | Refusals kept |",
        "|---|---:|---:|---:|---:|---:|---:|",
        f"| Development (written by me, tuned on) | {dev['questions']} | {dev['correct']} | "
        f"{dev['answered_when_it_should_not']} | {dev['handed_over_when_it_could_answer']} | "
        f"{dev['answered_from_the_wrong_section']} | {dev['refusals_kept']} of {dev['refusals_expected']} |",
    ]
    for name, h in res["assistant_heldout"].items():
        fr = first_run(name)
        if fr:
            x = fr["results"]
            out.append(
                f"| Held-out {name}, first run (commit {fr['commit']}) | {x['questions']} | {x['correct']} | "
                f"{x['answered_when_it_should_not']} | {x['handed_over_when_it_could_answer']} | "
                f"{x['answered_from_the_wrong_section']} | {x['refusals_kept']} of {x['refusals_expected']} |"
            )
        x = h["latest"]
        out.append(
            f"| Held-out {name}, latest (status: {h['status']}) | {x['questions']} | {x['correct']} | "
            f"{x['answered_when_it_should_not']} | {x['handed_over_when_it_could_answer']} | "
            f"{x['answered_from_the_wrong_section']} | {x['refusals_kept']} of {x['refusals_expected']} |"
        )
    s = res["sync"]
    out += [
        "",
        "## Payroll sync",
        "",
        f"First run: {s['first_run_items']} items ({s['change_requests']} change requests to the payroll provider, "
        f"{s['people_tickets']} tickets for the People team). Second run: {s['second_run_items']} items. "
        f"{s['provider_calls']} provider calls, including a deliberate retry, created {s['change_requests']} "
        f"requests.",
        "",
        f"Audit trail: {res['audit']['entries']} entries, chain intact: {res['audit']['chain_intact']}.",
        "",
    ]
    return "\n".join(out)


