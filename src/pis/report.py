def trend_svg(trend: list[dict[str, Any]]) -> str:
    if not trend:
        return '<p class="sub">No headcount history yet.</p>'
    w, h, pad = 620, 220, 40
    hc = [t["headcount"] for t in trend]
    lo, hi = min(hc) - 5, max(hc) + 5
    xs = [pad + i * (w - 2 * pad) / max(len(hc) - 1, 1) for i in range(len(hc))]
    ys = [h - pad - (v - lo) / (hi - lo) * (h - 2 * pad) for v in hc]
    pts = " ".join(f"{x:.1f},{y:.1f}" for x, y in zip(xs, ys))
    labels = "".join(
        f'<text x="{xs[i]:.1f}" y="{h - 12}" text-anchor="middle">{trend[i]["month"][2:]}</text>'
        for i in range(0, len(hc), 4)
    )
    ticks = "".join(
        f'<line class="grid" x1="{pad}" x2="{w - pad}" y1="{y:.1f}" y2="{y:.1f}"/>'
        f'<text x="{pad - 6}" y="{y + 4:.1f}" text-anchor="end">{v:.0f}</text>'
        for v, y in (
            (lo + 5, h - pad - 5 / (hi - lo) * (h - 2 * pad)),
            (hi - 5, h - pad - (hi - 5 - lo) / (hi - lo) * (h - 2 * pad)),
        )
    )
    return (
        f'<svg viewBox="0 0 {w} {h}" class="chart" role="img" aria-label="Headcount by month">{ticks}'
        f'<polyline class="line" points="{pts}"/><circle class="dot" cx="{xs[-1]:.1f}" cy="{ys[-1]:.1f}" r="4"/>'
        f"{labels}</svg>"
    )


def gap_svg(depts: list[dict[str, Any]], threshold: float) -> str:
    rows = [d for d in depts if not d["suppressed"]]
    w, row_h, left = 620, 30, 150
    h = row_h * len(rows) + 40
    lo, hi = -0.25, 0.32
    sx = lambda v: left + (v - lo) / (hi - lo) * (w - left - 20)  # noqa: E731
    out = [
        f'<line class="grid" x1="{sx(0):.1f}" x2="{sx(0):.1f}" y1="0" y2="{h - 26}"/>',
        f'<line class="thr" x1="{sx(threshold):.1f}" x2="{sx(threshold):.1f}" y1="0" y2="{h - 26}"/>',
        f'<text x="{sx(threshold) + 4:.1f}" y="{h - 10}">5% threshold</text>',
        f'<text x="{sx(0):.1f}" y="{h - 10}" text-anchor="middle">0</text>',
    ]
    for i, d in enumerate(sorted(rows, key=lambda r: -r["adjusted_gap"])):
        y = 14 + i * row_h
        a, b = d["interval"]
        cls = "warn" if d["evidence"] else "dot"
        out.append(
            f'<text x="{left - 10}" y="{y + 4}" text-anchor="end">{html.escape(d["department"])}</text>'
            f'<line class="ci" x1="{sx(max(a, lo)):.1f}" x2="{sx(min(b, hi)):.1f}" y1="{y}" y2="{y}"/>'
            f'<circle class="{cls}" cx="{sx(d["adjusted_gap"]):.1f}" cy="{y}" r="5">'
            f"<title>{d['department']}: {pct(d['adjusted_gap'])}</title></circle>"
        )
    return f'<svg viewBox="0 0 {w} {h}" class="chart" role="img" aria-label="Adjusted pay gap by department">{"".join(out)}</svg>'


