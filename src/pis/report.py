        f"<tr><td>{labels[k]}</td><td>{d[k]['planted']}</td><td>{d[k]['found']}</td>"
        f'<td class="{"ok" if d[k]["recall"] == 1 else "bad"}">{d[k]["true_positives"]}</td></tr>'
