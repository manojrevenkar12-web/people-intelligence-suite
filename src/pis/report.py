def build() -> None:
    res = json.loads((REPORTS / "results.json").read_text())
    stake = money_at_stake()
    (REPORTS / "REPORT.md").write_text(markdown(res, stake))
    (REPORTS / "dashboard.html").write_text(dashboard(res, stake))
    write_hyper(extract_tables(res.get("pay_gap_detail")))
